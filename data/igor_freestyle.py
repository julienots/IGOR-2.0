FREESTYLE = [
    ("C'est quoi le freestyle en street workout ?",
     "Le freestyle, ce sont les figures dynamiques et aériennes à la barre : swings, rotations "
     "autour de la barre, lâchers et rattrapages, 180, 360, sauts entre les barres, sorties "
     "acrobatiques. En compétition, on enchaîne ces figures dans un passage chronométré, et les "
     "juges notent la difficulté, l'exécution, la fluidité des enchaînements, la créativité et "
     "la variété."),
    ("Par quoi commencer en freestyle ?",
     "Les bases :\n1. Un swing (balancier) propre et contrôlé, épaules actives.\n2. Muscle-up "
     "fluide, plusieurs reps d'affilée.\n3. Rotations autour de la barre : pull-over (passer "
     "au-dessus de la barre), tours d'appui en arrière (back hip circle).\n4. Les premiers lâchers "
     "simples : clap muscle-up, swing avec lâcher et rattrapage.\n5. Les sorties (dismounts) en "
     "toute sécurité.\nTravaille sur une barre pas trop haute, avec un sol amortissant, et "
     "apprends à tomber avant d'apprendre à voler."),
    ("Comment faire un 180 à la barre ?",
     "Le 180 : pendant le swing, tu lâches la barre au sommet du balancier, tu fais un demi-tour "
     "et tu la rattrapes de l'autre côté.\nÉtapes :\n- maîtrise un swing ample et régulier ;\n- "
     "entraîne le changement de prise (un bras puis l'autre) sur le point mort du balancier ;\n- "
     "tourne la tête et les épaules dans le sens de la rotation ;\n- garde le corps gainé, regarde "
     "la barre pour le rattrapage.\nCommence sur une barre basse et progresse vers le lâcher "
     "complet."),
    ("Comment faire un 360 à la barre ?",
     "Le 360 au swing, c'est un tour complet en l'air avant de rattraper la barre. Prérequis : un "
     "180 parfaitement maîtrisé, un swing puissant et une bonne conscience aérienne.\nConseils :\n"
     "- lâche au point le plus haut du swing avant, quand tu as le plus de hauteur ;\n- groupe les "
     "bras près du corps pour tourner plus vite ;\n- engage la rotation avec la tête et les "
     "épaules ;\n- ouvre les bras tôt pour le rattrapage.\nTravaille d'abord les rotations au sol "
     "ou sur trampoline. Ensuite viennent les 540 et 720 pour les plus avancés."),
    ("C'est quoi un 540 ?",
     "Le 540, c'est une rotation et demie (540°) en l'air pendant un lâcher de barre. Il demande "
     "plus de hauteur et une rotation plus rapide que le 360. Ne le tente qu'avec un 360 constant "
     "et sécurisé. Les athlètes de haut niveau vont jusqu'au 720, voire au-delà, qui figurent "
     "parmi les mouvements les plus difficiles du freestyle."),
    ("C'est quoi le around the world ?",
     "Le around the world, c'est un passage du corps autour de la barre : depuis l'appui, tu fais "
     "passer les jambes et le corps par-dessus la barre puis tu reviens en appui, en changeant de "
     "prise si nécessaire. Il demande un bon gainage, de la coordination et des épaules mobiles. "
     "Commence par les tours d'appui (hip circles) et les passages de jambes par-dessus la barre."),
    ("C'est quoi un underswitch ?",
     "L'underswitch est une figure de freestyle où tu passes sous la barre en changeant de prise "
     "pendant le balancier, pour te retrouver face à l'autre côté. Il faut un swing parfaitement "
     "contrôlé et une bonne gestion des changements de mains. Apprends-le en décomposant : swing, "
     "lâcher d'une main, rotation, rattrapage."),
    ("C'est quoi le giant swing ?",
     "Le giant swing (grand tour), c'est faire un tour complet autour de la barre, bras tendus, "
     "corps tendu. En gymnastique on l'utilise avec des maniques et une barre adaptée. Sur une "
     "barre de street workout fixe, c'est plus risqué : prise solide, magnésie, et apprends d'abord "
     "avec une sangle ou sous la supervision d'un coach. Ne le tente jamais sans maîtriser les "
     "chutes."),
    ("Comment faire une sortie (dismount) en sécurité ?",
     "La règle : n'essaie une sortie acrobatique que si tu sais la faire au sol ou sur trampoline. "
     "Commence par un lâcher simple au bout du swing arrière, pieds devant, atterrissage genoux "
     "fléchis. Ensuite seulement les sorties avec rotation (salto arrière, vrille). Utilise des "
     "tapis, et entraîne-toi avec quelqu'un au début."),
    ("Comment améliorer mon swing ?",
     "- Pars d'une suspension active, épaules engagées.\n- Alterne creux (hollow) et cambré (arch) "
     "avec le corps entier, pas seulement les jambes.\n- Synchronise : poussée des jambes en "
     "avant, tirage léger des épaules au point haut.\n- Garde la prise ferme et les bras tendus.\n"
     "Exercice : 3 à 5 séries de 10 swings en cherchant l'amplitude et la régularité, sans "
     "à-coups."),
    ("Comment rendre mes figures freestyle plus fluides ?",
     "La fluidité vient de l'enchaînement :\n- Chaque figure doit finir dans la position de départ "
     "de la suivante.\n- Travaille les combos par blocs de 2 ou 3 figures, puis assemble.\n- Garde "
     "l'élan : évite les arrêts et les repositionnements inutiles.\n- Filme-toi pour repérer les "
     "temps morts.\nLa fluidité est un critère clé en compétition."),
]

