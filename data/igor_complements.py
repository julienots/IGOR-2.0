    ("Quelles sont les erreurs fréquentes en front lever ?",
     "Les plus courantes :\n- Hanches qui tombent sous l'horizontale.\n- Bras pliés.\n- Épaules qui "
     "montent vers les oreilles (pas de dépression).\n- Dos rond en tuck au lieu d'un dos plat.\n- "
     "Négliger la force de traction de base.\nVérifie de profil : épaules, hanches et pieds doivent être "
     "alignés à l'horizontale."),
    ("Quelles sont les erreurs fréquentes au muscle-up ?",
     "- Tirer vers le menton au lieu de la poitrine.\n- Barre trop loin du corps.\n- Coudes qui "
     "s'ouvrent trop pendant la transition.\n- Un seul bras qui passe avant l'autre (chicken wing) : à "
     "éviter, c'est mauvais pour les épaules.\n- Kipping exagéré qui cache un manque de force.\nTravaille "
     "les tractions explosives et la transition sur barre basse."),
    ("Quelles sont les erreurs fréquentes en handstand ?",
     "- Dos cambré (banane) au lieu d'un corps aligné.\n- Épaules fermées : il faut pousser le sol et "
     "ouvrir les épaules.\n- Regarder trop loin devant.\n- Corriger avec tout le corps au lieu des "
     "doigts.\n- S'entraîner seulement contre le mur.\nPour l'alignement, entraîne-toi ventre face au mur."),
