    # --- Figures complémentaires ---
    ("C'est quoi le muscle-up aux anneaux ?",
     "C'est un muscle-up où l'on utilise un false grip pour passer au-dessus des anneaux. Il est plus "
     "technique que sur barre car les anneaux bougent, mais plus doux pour les poignets. Prérequis : "
     "false grip tenu, tractions false grip, et dips aux anneaux stables."),
    ("C'est quoi le pull-over ?",
     "Le pull-over, c'est passer de la suspension à l'appui au-dessus de la barre en faisant passer les "
     "hanches par-dessus, en tirant la barre vers les hanches. C'est une base du freestyle et la "
     "première façon de monter sur la barre sans muscle-up."),
    ("C'est quoi le back hip circle ?",
     "Le back hip circle (tour d'appui arrière) : en appui sur la barre, hanches contre la barre, tu "
     "pars en arrière et fais un tour complet autour de la barre pour revenir en appui. C'est une "
     "figure de base du freestyle, qui apprend à tourner autour de la barre."),
    ("C'est quoi le kipping ?",
     "Le kipping, c'est utiliser l'élan du corps (un mouvement de vague) pour aider une traction ou un "
     "muscle-up. C'est utile en freestyle et pour l'endurance, mais il ne remplace pas la force stricte. "
     "En compétition de force, les mouvements doivent souvent être stricts."),
    ("C'est quoi les tractions explosives ?",
     "Ce sont des tractions faites le plus vite possible, en cherchant à monter la poitrine au-dessus "
     "de la barre. Variantes : chest-to-bar, tractions claquées, tractions jusqu'à la taille. Elles "
     "sont essentielles pour le muscle-up et le freestyle : 4 à 6 séries de 3 à 5 reps, repos complet."),
    ("C'est quoi le bridge ?",
     "Le bridge (pont), c'est une position où tu es en appui sur les mains et les pieds, le ventre vers "
     "le ciel, la colonne arquée. Il développe la mobilité des épaules et du dos, utile pour le "
     "handstand et la santé de la colonne. Progresse doucement depuis le pont sur la tête ou contre un mur."),
    ("C'est quoi la V-sit ?",
     "La V-sit, c'est une L-sit où les jambes montent au-dessus de l'horizontale, formant un V avec le "
     "buste. Elle demande une compression et une souplesse des ischios importantes. Elle se place entre "
     "la L-sit et la manna dans la progression."),
    ("C'est quoi le dead hang ?",
     "Le dead hang est la suspension passive à la barre, bras tendus et épaules relâchées. Il "
     "renforce la prise et décompresse la colonne. L'active hang (épaules abaissées) est la position "
     "de départ correcte des tractions et du front lever."),
    ("C'est quoi le frog stand ?",
     "Le frog stand, c'est un équilibre sur les mains, genoux posés sur les coudes, bras tendus ou "
     "légèrement fléchis. C'est une étape avant la tuck planche : il apprend à porter le poids vers "
     "l'avant. Objectif : 30 s stable, puis essaie de décoller les genoux des coudes."),
    ("C'est quoi le planche lean ?",
     "Le planche lean, c'est une position de pompe bras tendus où tu avances les épaules au-delà des "
     "mains, en protraction. C'est l'exercice de base de la planche : il conditionne les poignets, les "
     "épaules et les biceps. 3 à 5 x 15-30 s, en augmentant l'inclinaison progressivement."),
    ("C'est quoi l'archer pull-up ?",
     "L'archer pull-up : prise large, tu tires vers une main pendant que l'autre bras reste presque "
     "tendu sur la barre. C'est une progression vers la traction à un bras. 3 à 5 x 3-6 reps par côté."),
    ("C'est quoi les ice cream makers ?",
     "Les ice cream makers : depuis la suspension, tu montes en front lever bras tendus, puis tu tires "
     "en traction en restant horizontal, et tu redescends. Ils combinent front lever et traction, "
     "excellents pour la force de tirage. Commence en tuck."),
    ("C'est quoi le support hold ?",
     "Le support hold, c'est tenir le haut d'un dip, bras tendus, aux barres parallèles ou aux anneaux, "
     "épaules abaissées. C'est la base de la force en bras tendus et de la stabilité, avant les dips, "
     "le L-sit et les anneaux. 3 x 30-60 s."),
    ("C'est quoi un dip sur barre droite ?",
     "C'est un dip réalisé au-dessus d'une barre unique, buste penché en avant. Il est indispensable "
     "pour finir le muscle-up sur barre. Commence en appui au-dessus de la barre et fais des négatives "
     "si besoin."),
    ("C'est quoi la différence entre street workout et calisthenics ?",
     "Ce sont presque des synonymes. Calisthenics désigne l'entraînement au poids du corps en général. "
     "Street workout désigne plutôt la pratique en extérieur, sur les barres des parcs, avec une forte "
     "culture freestyle et compétition. Les figures sont les mêmes."),
